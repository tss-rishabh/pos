// Package posstock is the POS exchange compatibility transaction. It contains no
// network side effects and never infers a stock decrement from a payment status.
package posstock

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
)

const Contract = "pos-exchange-stock-v1"

var ErrReview = errors.New("POS exchange requires reconciliation")

type Confirmation struct {
	Created   bool
	ProductID int64
}

type link struct {
	ParentOrderID, ParentLineID, LineID, ProductID, Quantity, StoreID, CounterID, CustomerID int64
}

// Confirm returns only after stock, line placement, paid status and proof commit
// together. The child row serializes all retries, including a lost COMMIT reply.
// A legacy partially paid child without proof is deliberately refused.
func Confirm(ctx context.Context, db *sql.DB, orderID int64) (Confirmation, error) {
	if orderID < 1 {
		return Confirmation{}, ErrReview
	}
	tx, err := db.BeginTx(ctx, &sql.TxOptions{Isolation: sql.LevelRepeatableRead})
	if err != nil {
		return Confirmation{}, err
	}
	defer tx.Rollback()
	var parentID, customerID, method, paid, status int64
	var payable float64
	if err = tx.QueryRowContext(ctx, `SELECT parent_order_id,user_id,payment_method,pay_amt,payment_status,order_status FROM orders WHERE id=? FOR UPDATE`, orderID).Scan(&parentID, &customerID, &method, &payable, &paid, &status); err != nil {
		return Confirmation{}, err
	}
	if parentID < 1 || customerID < 1 || method != 3 || payable != 0 {
		return Confirmation{}, ErrReview
	}
	rows, err := tx.QueryContext(ctx, `SELECT e.parent_order_id,e.parent_has_product_id,h.id,h.prod_id,h.qty,s.store_id,s.counter_id,p.user_id,ph.prod_id,ph.qty,ph.status,h.status FROM exchange_order_log e JOIN has_products h ON h.id=e.has_product_id AND h.order_id=e.order_id JOIN has_products ph ON ph.id=e.parent_has_product_id AND ph.order_id=e.parent_order_id JOIN order_stores s ON s.order_id=e.order_id JOIN orders p ON p.id=e.parent_order_id WHERE e.order_id=? FOR UPDATE`, orderID)
	if err != nil {
		return Confirmation{}, err
	}
	var selected link
	var parentProduct, parentQuantity int64
	var parentStatus, childStatus string
	if !rows.Next() {
		err = rows.Err()
		rows.Close()
		if err != nil {
			return Confirmation{}, err
		}
		return Confirmation{}, ErrReview
	}
	if err = rows.Scan(&selected.ParentOrderID, &selected.ParentLineID, &selected.LineID, &selected.ProductID, &selected.Quantity, &selected.StoreID, &selected.CounterID, &selected.CustomerID, &parentProduct, &parentQuantity, &parentStatus, &childStatus); err != nil {
		rows.Close()
		return Confirmation{}, err
	}
	duplicate := rows.Next()
	rowErr := rows.Err()
	closeErr := rows.Close()
	if rowErr != nil {
		return Confirmation{}, rowErr
	}
	if closeErr != nil {
		return Confirmation{}, closeErr
	}
	if duplicate || selected.ParentOrderID != parentID || selected.CustomerID != customerID || selected.ParentLineID < 1 || selected.LineID < 1 || selected.ProductID < 1 || selected.Quantity < 1 || selected.Quantity != parentQuantity || selected.StoreID < 1 || selected.CounterID < 1 {
		return Confirmation{}, ErrReview
	}
	var acceptedReturns int64
	if err = tx.QueryRowContext(ctx, `SELECT COUNT(*) FROM return_orders WHERE order_id=? AND has_product_id=? AND prod_id=? AND store_id=? AND credit_note_no<>''`, parentID, selected.ParentLineID, parentProduct, selected.StoreID).Scan(&acceptedReturns); err != nil {
		return Confirmation{}, err
	}
	if acceptedReturns < 1 {
		return Confirmation{}, ErrReview
	}
	// Lock all child lines: this compatibility contract supports the single paid
	// replacement generated by PosExchangeOrder, without silently placing extras.
	items, err := tx.QueryContext(ctx, `SELECT id FROM has_products WHERE order_id=? FOR UPDATE`, orderID)
	if err != nil {
		return Confirmation{}, err
	}
	var itemID int64
	count := 0
	for items.Next() {
		if err = items.Scan(&itemID); err != nil {
			items.Close()
			return Confirmation{}, err
		}
		count++
		if itemID != selected.LineID {
			items.Close()
			return Confirmation{}, ErrReview
		}
	}
	rowErr = items.Err()
	closeErr = items.Close()
	if rowErr != nil {
		return Confirmation{}, rowErr
	}
	if closeErr != nil {
		return Confirmation{}, closeErr
	}
	if count != 1 {
		return Confirmation{}, ErrReview
	}
	var proof link
	var version string
	err = tx.QueryRowContext(ctx, `SELECT parent_order_id,parent_has_product_id,has_product_id,product_id,quantity,store_id,counter_id,contract_version FROM pos_rewrite_exchange_stock_confirmations WHERE order_id=? FOR UPDATE`, orderID).Scan(&proof.ParentOrderID, &proof.ParentLineID, &proof.LineID, &proof.ProductID, &proof.Quantity, &proof.StoreID, &proof.CounterID, &version)
	if err == nil {
		proof.CustomerID = selected.CustomerID
		if proof != selected || version != Contract || paid != 4 || (status != 1 && status != 3) || (childStatus != "PLACED" && childStatus != "DELIVERED") {
			return Confirmation{}, ErrReview
		}
		if err = tx.Commit(); err != nil {
			return Confirmation{}, err
		}
		return Confirmation{ProductID: selected.ProductID}, nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return Confirmation{}, err
	}
	if paid != 0 || status != 0 || parentStatus != "EXCHANGE_INITIATED" {
		return Confirmation{}, ErrReview
	}
	// The parent line was locked by the linkage query. Serialize different
	// children for that same return too: a Redis TTL cannot provide this.
	var otherChild int64
	err = tx.QueryRowContext(ctx, `SELECT p.order_id FROM pos_rewrite_exchange_stock_confirmations p JOIN orders o ON o.id=p.order_id WHERE p.parent_order_id=? AND p.parent_has_product_id=? AND p.order_id<>? AND (o.order_status IS NULL OR o.order_status NOT IN (4,22)) LIMIT 1 FOR UPDATE`, selected.ParentOrderID, selected.ParentLineID, orderID).Scan(&otherChild)
	if err == nil {
		return Confirmation{}, ErrReview
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return Confirmation{}, err
	}
	stocks, err := tx.QueryContext(ctx, `SELECT id,stock,is_avail,is_del FROM product_store WHERE store_id=? AND product_id=? FOR UPDATE`, selected.StoreID, selected.ProductID)
	if err != nil {
		return Confirmation{}, err
	}
	var stockID, stock int64
	var available, deleted bool
	if !stocks.Next() {
		err = stocks.Err()
		stocks.Close()
		if err != nil {
			return Confirmation{}, err
		}
		return Confirmation{}, ErrReview
	}
	if err = stocks.Scan(&stockID, &stock, &available, &deleted); err != nil {
		stocks.Close()
		return Confirmation{}, err
	}
	duplicate = stocks.Next()
	rowErr = stocks.Err()
	closeErr = stocks.Close()
	if rowErr != nil {
		return Confirmation{}, rowErr
	}
	if closeErr != nil {
		return Confirmation{}, closeErr
	}
	if duplicate || !available || deleted || stock < selected.Quantity {
		return Confirmation{}, ErrReview
	}
	result, err := tx.ExecContext(ctx, `UPDATE product_store SET stock=stock-? WHERE id=? AND store_id=? AND product_id=? AND stock>=? AND is_avail=1 AND is_del=0`, selected.Quantity, stockID, selected.StoreID, selected.ProductID, selected.Quantity)
	if err != nil {
		return Confirmation{}, err
	}
	affected, err := result.RowsAffected()
	if err != nil {
		return Confirmation{}, err
	}
	if affected != 1 {
		return Confirmation{}, ErrReview
	}
	if _, err = tx.ExecContext(ctx, `UPDATE has_products SET status='PLACED' WHERE id=? AND order_id=?`, selected.LineID, orderID); err != nil {
		return Confirmation{}, err
	}
	result, err = tx.ExecContext(ctx, `UPDATE orders SET order_status=1,payment_status=4 WHERE id=? AND order_status=0 AND payment_status=0`, orderID)
	if err != nil {
		return Confirmation{}, err
	}
	affected, err = result.RowsAffected()
	if err != nil {
		return Confirmation{}, err
	}
	if affected != 1 {
		return Confirmation{}, ErrReview
	}
	if _, err = tx.ExecContext(ctx, `INSERT INTO pos_rewrite_exchange_stock_confirmations (order_id,parent_order_id,parent_has_product_id,has_product_id,store_id,counter_id,product_id,quantity,contract_version,confirmed_at) VALUES (?,?,?,?,?,?,?,?,?,CURRENT_TIMESTAMP)`, orderID, selected.ParentOrderID, selected.ParentLineID, selected.LineID, selected.StoreID, selected.CounterID, selected.ProductID, selected.Quantity, Contract); err != nil {
		return Confirmation{}, fmt.Errorf("stock proof: %w", err)
	}
	if err = tx.Commit(); err != nil {
		return Confirmation{}, err
	}
	return Confirmation{Created: true, ProductID: selected.ProductID}, nil
}
