"""Pinned API-v2 producer patch and shared native fence constants.

Default compares artifacts without writes. --write updates only target rewrite
files. Both protected upstream repositories remain untouched.
"""

import argparse
import ast
import hashlib
import json
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from membership_fence import definitions, CONTRACT

COMMIT = "2960acbea10c4eaf16b6d99e15ff6e03ef7724c5"
MUTATORS = {
    "set_exclusive_user",
    "set_exclusive_expiry",
    "set_exclusive_upgrade_user",
    "set_exclusive_upgrade_expiry",
    "set_exclusive_user_check",
    "set_exclusive_expiry_check",
    "set_exclusive_upgrade_user_check",
    "set_exclusive_upgrade_expiry_check",
}


def source(path):
    repo = ROOT.parents[4] / "backend-tss-api_v2"
    return subprocess.check_output(["git", "show", COMMIT + ":" + path], cwd=repo, text=True)


def api_candidates():
    dal = source("controllers/user/userDal.py")
    if (
        hashlib.sha256(dal.encode()).hexdigest()
        != "ad0135cb60aa2c8ffd8d5aa5bc6d8b343efb97227fd3394a1ff31989054141a8"
    ):
        raise RuntimeError("Membership source helper changed")
    parsed = ast.parse(dal)
    actual = {
        node.name
        for node in parsed.body
        if isinstance(node, ast.FunctionDef) and node.name in MUTATORS
    }
    if actual != MUTATORS:
        raise RuntimeError("Membership source writer inventory changed")
    after = (
        "from middleware.PosMembershipProvenance import membership_user_lock, defer_membership_invalidation\n"
        + dal
    )
    for name in sorted(MUTATORS):
        marker = "def " + name + "("
        if after.count(marker) != 1:
            raise RuntimeError("Membership helper binding changed")
        after = after.replace(marker, "@membership_user_lock\n" + marker, 1)
    after = after.replace(
        "cache.region_invalidate(",
        "defer_membership_invalidation(session, cache.region_invalidate, ",
    )
    # Notify-only code is not decorated and has no membership invalidation call.
    controller = source("controllers/OrderController.py")
    if (
        hashlib.sha256(controller.encode()).hexdigest()
        != "821ee475e4e19d0f48c1078e0eaf6dc0f17fbd57506d0e97f125be45b26746ad"
    ):
        raise RuntimeError("Order controller source changed")
    start = controller.index(
        "        if exclusive_user and not exclusive_user.get('store_exclusive',0):",
        controller.index("class PosOrder"),
    )
    end = controller.index("\n        # make_assign_warehouse_request(order)", start)
    original = controller[start:end]
    block = original.replace(
        "set_exclusive_user(session,", "set_exclusive_user(member_stage.session,"
    ).replace(
        "set_exclusive_upgrade_user(session,", "set_exclusive_upgrade_user(member_stage.session,"
    )
    if block == original:
        raise RuntimeError("PosOrder staging writers changed")
    wrapped = "        with membership_order_stage(session, order.id, user, settings) as member_stage:\n            if member_stage.apply:\n" + "".join(
        "        " + line + "\n" if line else "\n" for line in block.splitlines()
    ).rstrip(
        "\n"
    )
    candidate = (
        "from middleware.PosMembershipProvenance import membership_order_stage\n"
        + controller[:start]
        + wrapped
        + controller[end:]
    )
    ast.parse(after)
    ast.parse(candidate)
    return {
        "controllers/user/userDal.py": (dal, after),
        "controllers/OrderController.py": (controller, candidate),
    }


def outputs():
    import difflib

    values = definitions()
    py = (
        '"""Generated from the reviewed native membership fence; no live discovery."""\nFENCE_CONTRACT='
        + repr(CONTRACT)
        + "\nDEFINITIONS="
        + repr(values)
        + "\n"
    )
    ts = (
        "// Generated by prepare_membership_producers.py from the review-only SQL.\nexport const nativeMembershipFenceContract = "
        + json.dumps(CONTRACT)
        + ";\nexport const nativeMembershipFenceDefinitions = "
        + json.dumps(values, indent=2)
        + " as const;\n"
    )
    go = (
        "// Generated by prepare_membership_producers.py from the reviewed SQL.\npackage poscheckout\n\nconst MembershipFenceContract = "
        + json.dumps(CONTRACT)
        + "\n\nvar membershipFenceDefinitions = []membershipFenceDefinition{\n"
        + "".join(
            "\t{"
            + ", ".join(
                json.dumps(item[key]) for key in ("name", "event", "table", "timing", "hash")
            )
            + "},\n"
            for item in values
        )
        + "}\n"
    )
    changes = api_candidates()
    helper = (
        (ROOT / "membership_provenance.py")
        .read_text()
        .replace(
            "from membership_fence_contract import", "from middleware.PosMembershipFence import"
        )
    )
    patch = "".join(
        "".join(
            difflib.unified_diff(
                before.splitlines(True),
                after.splitlines(True),
                fromfile="a/" + path,
                tofile="b/" + path,
            )
        )
        for path, (before, after) in changes.items()
    )
    for filename, body in [
        ("middleware/PosMembershipProvenance.py", helper),
        ("middleware/PosMembershipFence.py", py),
    ]:
        patch += "".join(
            difflib.unified_diff(
                [], body.splitlines(True), fromfile="/dev/null", tofile="b/" + filename
            )
        )
    manifest = {
        "sourceCommit": COMMIT,
        "stagedContract": "pos-cancellation-membership-staged-v2",
        "activatedContract": "pos-cancellation-membership-provenance-v2",
        "nativeFence": CONTRACT,
        "sourceSha256": {
            path: hashlib.sha256(before.encode()).hexdigest()
            for path, (before, _) in changes.items()
        },
        "candidateSha256": {
            path: hashlib.sha256(after.encode()).hexdigest() for path, (_, after) in changes.items()
        },
        "helperSha256": hashlib.sha256(helper.encode()).hexdigest(),
        "patch": "api-v2-membership-producers.patch",
        "patchSha256": hashlib.sha256(patch.encode()).hexdigest(),
        "enabled": False,
    }
    return {
        ROOT / "membership_fence_contract.py": py,
        ROOT.parents[2] / "src/modules/checkout/cancellations/membership-fence-contract.ts": ts,
        ROOT.parent / "go/internal/poscheckout/membership_fence_contract.go": go,
        ROOT / "api-v2-membership-producers.patch": patch,
        ROOT / "membership-producer-manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    for path, body in outputs().items():
        if args.write:
            path.write_text(body)
        elif not path.exists() or path.read_text() != body:
            raise RuntimeError("Membership producer artifact changed: " + str(path.name))
        print(path.name + " " + hashlib.sha256(body.encode()).hexdigest())
