import {
  bigint,
  datetime,
  double,
  float,
  int,
  mysqlEnum,
  mysqlTable,
  text,
  tinyint,
  varchar,
} from 'drizzle-orm/mysql-core';
import { voucherHistoryPlatforms } from '../../db/legacy-enums.js';

/** Verified physical columns, except the explicitly gated nullable validity correction. */
export const globalCoupons = mysqlTable('coupons', {
  id: int('id').autoincrement().primaryKey(),
  userId: bigint('user_id', { mode: 'bigint' }).notNull(),
  fromId: varchar('from_id', { length: 255 }).notNull(),
  fromName: varchar('from_name', { length: 100 }).notNull(),
  toId: varchar('to_id', { length: 255 }).notNull(),
  toName: varchar('to_name', { length: 100 }).notNull(),
  code: varchar('voucher_code', { length: 255 }).notNull(),
  name: varchar('voucher_name', { length: 200 }).notNull(),
  quantity: bigint('disc_apply_items', { mode: 'bigint' }).notNull(),
  type: varchar('voucher_type', { length: 255 }).notNull(),
  image: varchar('image', { length: 255 }).notNull(),
  offer: tinyint('is_offer').notNull(),
  validFor: int('voucher_valid_for').notNull(),
  value: int('voucher_val').notNull(),
  initialValue: double('initial_val').notNull(),
  specific: int('user_specific').notNull(),
  category: text('coupon_cat').notNull(),
  deleted: int('is_deleted').notNull(),
  internEmail: varchar('intern_email', { length: 255 }).notNull(),
  artist: text('for_artist').notNull(),
  remaining: float('remaining').notNull(),
  theme: varchar('theme', { length: 255 }).notNull(),
  message: varchar('message', { length: 255 }).notNull(),
  startsAt: datetime('start_date', { mode: 'string' }).notNull(),
  expiresAt: datetime('end_date', { mode: 'string' }).notNull(),
  minimum: float('min_order_amt').notNull(),
  count: int('no_times_allowed').notNull(),
  lot: varchar('coupon_lot_no', { length: 255 }).notNull(),
  paymentMethod: varchar('payment_method', { length: 255 }).notNull(),
  transactionId: varchar('transaction_id', { length: 255 }).notNull(),
  transactionStatus: varchar('transaction_status', { length: 255 }).notNull(),
  transactionOrderId: bigint('transaction_orderid', { mode: 'bigint' }).notNull(),
  requestedBy: varchar('requested_by', { length: 255 }).notNull(),
  newUser: tinyint('for_new_user').notNull(),
  userType: int('user_type').notNull(),
  percentageMaximum: varchar('voucher_percentage_max_val', { length: 255 }).notNull(),
  buyableQuantity: bigint('buyable_quantity', { mode: 'bigint' }).notNull(),
  freeQuantity: bigint('free_quantity', { mode: 'bigint' }).notNull(),
  mixedType: varchar('voucher_mxn_type', { length: 255 }).notNull(),
  createdAt: datetime('created_at', { mode: 'string' }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'string' }).notNull(),
});
export const globalVouchers = mysqlTable('gift_vouchers', {
  id: bigint('id', { mode: 'bigint' }).autoincrement().primaryKey(),
  customerId: bigint('from_id', { mode: 'bigint' }).notNull(),
  recipient: varchar('to_id', { length: 255 }).notNull(),
  code: varchar('voucher_code', { length: 25 }).notNull(),
  theme: int('theme').notNull(),
  name: varchar('to_name', { length: 100 }).notNull(),
  phone: bigint('to_phone', { mode: 'bigint' }).notNull(),
  value: double('voucher_value'),
  initialValue: double('voucher_initial_value'),
  message: text('message').notNull(),
  status: tinyint('status').notNull(),
  orderId: bigint('order_id', { mode: 'bigint' }).notNull(),
  couponId: bigint('coupon_id', { mode: 'bigint' }).notNull(),
  collectionId: bigint('collection_no', { mode: 'bigint' }).notNull(),
  kind: mysqlEnum('gv_type', ['GIFT_VOUCHER', 'GIFT_CARD']).notNull(),
  serial: bigint('gift_card_srno', { mode: 'bigint' }).notNull(),
  requiresPin: tinyint('is_gcpin').notNull(),
  platform: mysqlEnum('platform', ['both', 'offline', 'online']).notNull(),
  startsAt: datetime('start_date', { mode: 'string' }).notNull(),
  expiresAt: datetime('end_date', { mode: 'string' }).notNull(),
  createdAt: datetime('created_at', { mode: 'string' }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'string' }).notNull(),
});
export const globalVoucherHistory = mysqlTable('gift_voucher_history', {
  id: bigint('id', { mode: 'bigint' }).autoincrement().primaryKey(),
  userId: bigint('user_id', { mode: 'bigint' }).notNull(),
  orderId: bigint('order_id', { mode: 'bigint' }),
  voucherId: bigint('gv_id', { mode: 'bigint' }),
  amount: double('added_amt'),
  before: double('amt_before_update'),
  after: double('amt_after_update'),
  comment: text('comment'),
  // Legacy writes 'GV_ADD' (not a member); it is stored and written as ''.
  platform: mysqlEnum('platform', voucherHistoryPlatforms).$type<
    (typeof voucherHistoryPlatforms)[number] | ''
  >(),
  operatorId: bigint('added_user', { mode: 'bigint' }),
  createdAt: datetime('created_at', { mode: 'string' }),
  updatedAt: datetime('updated_at', { mode: 'string' }),
  bulk: tinyint('is_bulk_upload'),
});
