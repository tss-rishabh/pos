CREATE TABLE pos_rewrite_legacy_order_imports (
  sequence BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  id VARCHAR(36) NOT NULL,
  actor_id VARCHAR(32) NOT NULL,
  request_id VARCHAR(128) NULL,
  request_hash VARCHAR(64) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  state VARCHAR(16) NOT NULL,
  total_orders INT NOT NULL,
  imported_orders INT NOT NULL,
  failed_orders INT NOT NULL,
  cancelled_orders INT NOT NULL,
  error_code VARCHAR(64) NULL,
  claim_token VARCHAR(36) NULL,
  lease_until DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  completed_at DATETIME(3) NULL,
  UNIQUE KEY uq_legacy_order_import_id (id),
  KEY ix_legacy_order_import_queue (state,lease_until,sequence),
  KEY ix_legacy_order_import_owner (actor_id,sequence)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE pos_rewrite_legacy_order_import_rows (
  job_id VARCHAR(36) NOT NULL,
  sequence INT NOT NULL,
  first_row INT NOT NULL,
  operation_id VARCHAR(36) NOT NULL,
  store_id VARCHAR(32) NOT NULL,
  counter_id VARCHAR(32) NOT NULL,
  state VARCHAR(16) NOT NULL,
  payload MEDIUMTEXT NOT NULL,
  order_id VARCHAR(32) NULL,
  receipt_id VARCHAR(36) NULL,
  business_date VARCHAR(10) NULL,
  proof_hash VARCHAR(64) NULL,
  error_code VARCHAR(64) NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (job_id,sequence),
  UNIQUE KEY uq_legacy_order_import_operation (operation_id),
  UNIQUE KEY uq_legacy_order_import_order (order_id),
  UNIQUE KEY uq_legacy_order_import_receipt (receipt_id),
  KEY ix_legacy_order_import_pending (job_id,state,sequence)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
