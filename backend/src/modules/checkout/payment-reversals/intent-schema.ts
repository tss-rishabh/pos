import {
  bigint,
  char,
  date,
  datetime,
  index,
  int,
  json,
  mysqlTable,
  uniqueIndex,
  varchar,
} from 'drizzle-orm/mysql-core';
import type { CashReturnIntentBody, CashReturnAction } from './intent-contracts.js';
export const cashReturnIntents = mysqlTable(
  'pos_rewrite_cash_return_intents',
  {
    id: char('id', { length: 36 }).primaryKey(),
    orderId: varchar('order_id', { length: 32 }).notNull(),
    storeId: varchar('store_id', { length: 32 }).notNull(),
    counterId: varchar('counter_id', { length: 32 }).notNull(),
    preparedBy: varchar('prepared_by', { length: 32 }).notNull(),
    originalPaymentId: char('original_payment_id', { length: 36 }).notNull(),
    activePaymentId: char('active_payment_id', { length: 36 }),
    correctionId: char('correction_id', { length: 36 }).notNull(),
    cashReturnReceiptId: char('cash_return_receipt_id', { length: 36 }).notNull(),
    phase: varchar('phase', { length: 20 }).$type<CashReturnIntentBody['phase']>().notNull(),
    body: json('body').$type<CashReturnIntentBody>().notNull(),
    bodyHash: char('body_hash', { length: 64 }).notNull(),
    impactFrom: date('impact_from', { mode: 'string' }).notNull(),
    createdAt: datetime('created_at', { mode: 'string', fsp: 3 }).notNull(),
    updatedAt: datetime('updated_at', { mode: 'string', fsp: 3 }).notNull(),
  },
  (table) => [
    uniqueIndex('cash_return_active_payment').on(table.activePaymentId),
    uniqueIndex('cash_return_correction').on(table.correctionId),
    uniqueIndex('cash_return_receipt').on(table.cashReturnReceiptId),
    index('cash_return_pending_scope').on(table.storeId, table.phase, table.id),
    index('cash_return_order').on(table.orderId, table.id),
  ],
);
export const cashReturnCommands = mysqlTable(
  'pos_rewrite_cash_return_commands',
  {
    id: char('id', { length: 36 }).primaryKey(),
    intentId: char('intent_id', { length: 36 }).notNull(),
    kind: varchar('kind', { length: 16 }).$type<CashReturnAction>().notNull(),
    actorId: varchar('actor_id', { length: 32 }).notNull(),
    sessionHash: char('session_hash', { length: 64 }).notNull(),
    requestHash: char('request_hash', { length: 64 }).notNull(),
    body: json('body').$type<CashReturnIntentBody>().notNull(),
    bodyHash: char('body_hash', { length: 64 }).notNull(),
    requestId: varchar('request_id', { length: 128 }),
    proofHash: char('proof_hash', { length: 64 }).notNull(),
    recordedAt: datetime('recorded_at', { mode: 'string', fsp: 3 }).notNull(),
  },
  (table) => [index('cash_return_command_intent').on(table.intentId, table.recordedAt, table.id)],
);
export const cashReturnControls = mysqlTable('pos_rewrite_cash_return_controls', {
  storeId: varchar('store_id', { length: 32 }).primaryKey(),
  revision: bigint('revision', { mode: 'bigint', unsigned: true }).notNull(),
  manifestHash: char('manifest_hash', { length: 64 }).notNull(),
  unresolvedCount: int('unresolved_count', { unsigned: true }).notNull(),
  pendingFrom: date('pending_from', { mode: 'string' }),
  partitionCount: int('partition_count', { unsigned: true }).notNull(),
  partitionManifestHash: char('partition_manifest_hash', { length: 64 }).notNull(),
  proofHash: char('proof_hash', { length: 64 }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'string', fsp: 3 }).notNull(),
});
export const cashReturnPartitionControls = mysqlTable(
  'pos_rewrite_cash_return_partition_controls',
  {
    id: varchar('id', { length: 48 }).primaryKey(),
    storeId: varchar('store_id', { length: 32 }).notNull(),
    businessDate: date('business_date', { mode: 'string' }).notNull(),
    revision: bigint('revision', { mode: 'bigint', unsigned: true }).notNull(),
    manifestHash: char('manifest_hash', { length: 64 }).notNull(),
    financialFactCount: int('financial_fact_count', { unsigned: true }).notNull(),
    financialFactHash: char('financial_fact_hash', { length: 64 }).notNull(),
    proofHash: char('proof_hash', { length: 64 }).notNull(),
    updatedAt: datetime('updated_at', { mode: 'string', fsp: 3 }).notNull(),
  },
  (table) => [uniqueIndex('cash_return_partition_scope').on(table.storeId, table.businessDate)],
);
