"""Copy the portable offline-cash evidence contract; verification is read-only."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'backend/src/modules/checkout/offline-cash'
TARGET = ROOT / 'frontend/src/offline/cash'
HEADER = '// Generated by backend/tools/checkout/offline_contracts.py; edit the backend source.\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    arguments = parser.parse_args()
    for name in ['contracts.ts', 'canonical.ts', 'evidence.ts']:
        content = HEADER + (SOURCE / name).read_text()
        target = TARGET / name
        if arguments.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        elif not target.is_file() or target.read_text() != content:
            raise RuntimeError('The portable offline-cash contract differs: ' + name)
        print(name)
