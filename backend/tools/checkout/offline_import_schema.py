"""Generate the bounded cash importer ORM from saved physical MySQL metadata.

The only schema override is the separately reviewed nullable unset-event dates.
Verification is read-only by default; --write explicitly regenerates the file.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'src/modules/checkout/offline-cash/legacy-import-schema.ts'


def generate():
    physical = json.loads((ROOT / 'evidence/mysql-extra-schema.json').read_text())['tables']
    tables = {name: physical[name] for name in ('orders', 'has_products', 'order_stores')}
    digest = hashlib.sha256(json.dumps(tables, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    out = ["// Generated by tools/checkout/offline_import_schema.py from verified physical metadata.",
           "// Nullable unset event dates require pos-offline-cash-order-schema-v1; no DDL executes here.",
           "import { sql } from 'drizzle-orm';",
           "import { bigint, datetime, decimal, double, float, int, mysqlEnum, mysqlTable, text, tinyint, varchar } from 'drizzle-orm/mysql-core';",
           f"export const cashOrderPhysicalMetadataHash = '{digest}';"]
    metadata = {}
    for name, export in [('orders', 'cashOrders'), ('has_products', 'cashHasProducts'), ('order_stores', 'cashOrderStores')]:
        out.append(f"export const {export} = mysqlTable('{name}', {{")
        metadata[name] = {}
        for column in tables[name]:
            field, kind = column['name'], column['type']
            nullable = column['nullable'] or (name == 'orders' and field in ('ship_date', 'ret_ex_request_date'))
            if kind.startswith('enum('):
                expression = f"mysqlEnum('{field}', {json.dumps(kind[5:-1].replace(chr(39), '').split(','))})"
            elif kind.startswith('varchar('):
                expression = f"varchar('{field}', {{length:{int(kind[8:-1])}}})"
            elif kind.startswith('decimal('):
                precision, scale = kind[8:-1].split(',')
                expression = f"decimal('{field}', {{precision:{precision},scale:{scale}}})"
            elif kind == 'bigint':
                expression = f"bigint('{field}', {{mode:'bigint'}})"
            elif kind == 'datetime':
                expression = f"datetime('{field}', {{mode:'string'}})"
            elif kind.startswith('float('):
                expression = f"float('{field}')"
            elif kind.startswith('tinyint'):
                expression = f"tinyint('{field}')"
            elif kind in ('int', 'double', 'float', 'text'):
                expression = f"{kind}('{field}')"
            else:
                raise ValueError('Unsupported physical cash column: ' + name + '.' + field)
            auto = 'auto_increment' in column['extra']
            if auto:
                expression += '.autoincrement()'
            if column['key'] == 'PRI':
                expression += '.primaryKey()'
            if not nullable:
                expression += '.notNull()'
            if not auto and (column.get('default') is not None or nullable):
                # DEFAULT refers to the existing writer schema, without serializing
                # old zero dates or generated defaults as explicit parameters.
                expression += '.default(sql`DEFAULT`)'
            out.append(f"  {field}: {expression},")
            metadata[name][field] = {**column, 'nullable': nullable}
        out.append('});')
    out.append('export const cashPhysicalColumns = ' + json.dumps(metadata, indent=2) + ' as const;')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    arguments = parser.parse_args()
    result = generate()
    if arguments.write:
        TARGET.write_text(result)
    elif not TARGET.is_file() or TARGET.read_text() != result:
        raise RuntimeError('The cash importer physical ORM differs; regenerate explicitly.')
    print('cash importer physical ORM verified')
