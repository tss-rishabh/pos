"""Copy approved portable wallet schemas; default verification never rewrites files."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'backend/src/modules/checkout/benefit-adjustments'
TARGET = ROOT / 'frontend/src/offline/benefits'
HEADER = '// Generated by backend/tools/checkout/benefit_contracts.py; edit the backend source.\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    arguments = parser.parse_args()
    for name in ['fields.ts', 'contracts.ts']:
        content = HEADER + (SOURCE / name).read_text()
        target = TARGET / name
        if arguments.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        elif not target.is_file() or target.read_text() != content:
            raise RuntimeError('The portable wallet contract differs: ' + name)
        print(name)
