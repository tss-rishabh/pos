"""Freeze the original, pure SQL builders as parameterized TypeScript templates.

Do not simplify financial expressions here. Runtime parity tests cover the
report reducer; SQL and warehouse parity require separate database evidence.
"""
import ast
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
legacy = root.parent.parent / 'backend-pos-web'
source = legacy / 'report/report_queries.py'
tree = ast.parse(source.read_text())
allowed = [n for n in tree.body if isinstance(n, (ast.Assign, ast.FunctionDef))]
namespace = {}
exec(compile(ast.fix_missing_locations(ast.Module(body=allowed, type_ignores=[])), str(source), 'exec'), namespace)
settings = ast.parse((legacy / 'POSAdmin/settings.py').read_text())
ids = {}
for node in settings.body:
    if isinstance(node, ast.Assign):
        for name in node.targets:
            if isinstance(name, ast.Name) and name.id in ('MEMBERSHIP_PRODUCT_IDS', 'PACKAGING_PRODUCT_IDS'):
                ids[name.id] = ','.join(str(int(v)) for v in ast.literal_eval(node.value))
queries = {'excludedProducts': namespace['DAILY_STORE_EXCLUDED_PRODUCTS_SQL']}
for origin, key in [('store_orders', 'storeOrders'), ('online_orders', 'onlineOrders')]:
    base = namespace['daily_store_base_query'](origin, 1, '__EXCLUDED_PRODUCTS__')
    base = base.replace('%s', '__STORES__', 1)
    queries[key] = namespace['daily_store_rollup_query'](base, origin, ids['MEMBERSHIP_PRODUCT_IDS'], ids['PACKAGING_PRODUCT_IDS'])
out = root / 'src/modules/legacy-report-sql.ts'
out.write_text('// Source: backend-pos-web/report/report_queries.py\n// SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n// Generated by tools/generate_report_sql.py. SQL literals only; values bind at runtime.\nexport const legacyReportSql = ' + json.dumps(queries, indent=2) + ' as const;\n')
print(json.dumps({'templates': len(queries), 'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest()}))
