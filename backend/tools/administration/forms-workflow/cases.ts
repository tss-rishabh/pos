export function sourceCase(input: FormCase) {
  const value = input.values;
  const names: Readonly<Record<string, string>> =
    input.resource === 'operators'
      ? {
          firstName: 'first_name',
          lastName: 'last_name',
          email: 'email',
          phone: 'phone',
          role: 'role',
          contactEmail: 'contact_email',
          otpMethod: 'otp_method',
          userType: 'user_type',
          password: 'password1',
          confirmPassword: 'password2',
        }
      : {
          name: 'store_name',
          shortName: 'short_name',
          locationCode: 'location_code',
          type: 'type',
          category: 'category',
          phone: 'phone',
          email: 'email',
          latitude: 'latitude',
          longitude: 'longitude',
          address: 'address',
          alternateAddress: 'alt_address',
          city: 'city_name',
          state: 'state_name',
          cityId: 'city_id',
          stateId: 'state_id',
          countryId: 'country_id',
          pincode: 'pincode',
          gstin: 'gstin',
          dailyThreshold: 'per_day_threshold',
          hourlyThreshold: 'per_hour_threshold',
          slackUrl: 'slack_group_url',
          franchiseName: 'franchise_name',
          franchiseDescription: 'franchise_description',
          franchiseCin: 'cin_number',
        };
  const post: Record<string, string> = {};
  for (const [key, name] of Object.entries(names)) {
    if (value[key] !== undefined)
      post[
        (input.resource === 'operators' && input.action === 'create' ? 'userform-' : '') + name
      ] = value[key]!;
  }
  return {
    id: input.id,
    resource: input.resource,
    action: input.action,
    actorId: input.actorId,
    targetId: input.targetId,
    post,
    postal: input.postal ?? false,
  };
}
