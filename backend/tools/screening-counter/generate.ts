import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import {
  counterDefinitionHash,
  counterProcedure,
  counterTriggers,
  counterInstallationSql,
  counterTables,
  counterRequiredPrefixes,
  counterIndexSql,
} from '../../src/modules/legacy-order-imports/screening-counter/writers.js';
import {
  counterContract,
  counterPublicationContract,
  counterWritersContract,
  counterSourceCommit,
  counterSku,
} from '../../src/modules/legacy-order-imports/screening-counter/contracts.js';
import { counterPrivilegeSql } from '../../src/modules/legacy-order-imports/screening-counter/privileges.js';

const directory = resolve('compatibility/upstream/legacy-order-imports');
const metadataSource = readFileSync(resolve('compatibility/upstream/screening-origins/history-security.review.sql'), 'utf8');
const metadataMatch = /\nRETURN (.*?)\n\$\$/s.exec(metadataSource);
if (!metadataMatch) throw new Error('Missing fixed history metadata body');
const metadataBody = ('RETURN ' + metadataMatch[1]).split(/\s+/).join(' ').trim().replace(/;+$/, '');
const metadataHash = createHash('sha256').update(metadataBody).digest('hex');
const definition = {
  contract: counterContract,
  publicationContract: counterPublicationContract,
  writersContract: counterWritersContract,
  sourceCommit: counterSourceCommit,
  sku: counterSku,
  definitionHash: counterDefinitionHash,
  procedure: counterProcedure,
  triggers: counterTriggers,
  privilegeSql: counterPrivilegeSql,
  requiredPrefixes: counterRequiredPrefixes,
  indexSql: counterIndexSql,
};
const outputs = new Map([
  [
    resolve(directory, 'screening-counter-definition.json'),
    JSON.stringify(definition, null, 2) + '\n',
  ],
  [
    resolve(directory, 'screening_counter_definition.go'),
    '// Generated by tools/screening-counter/generate.ts; review only.\npackage poscheckout\n\nconst screeningCounterDefinitionJSON = ' +
      JSON.stringify(JSON.stringify(definition)) +
      '\n\nconst screeningCounterMetadataBodyHash = ' + JSON.stringify(metadataHash) + '\n',
  ],
  [
    resolve(directory, 'screening-counter.review.sql'),
    '-- Review-only. Independent publisher/baseline and all cooperating writer cutover required.\n-- Never apply automatically or with the supplied read-only credentials.\nDELIMITER $$\n' +
      counterInstallationSql.join('$$\n') +
      '$$\nDELIMITER ;\n',
  ],
  [
    resolve(directory, 'screening-counter-writers.review.sql'),
    '-- Review-only legacy-table trigger/definer cutover AFTER control-table migration.\n-- Never apply automatically; no application EXECUTE or projection DML.\nDELIMITER $$\n' +
      counterInstallationSql.slice(counterTables.length).join('$$\n') +
      '$$\nDELIMITER ;\n',
  ],
  [
    resolve('src/modules/legacy-order-imports/screening-counter/migration.sql'),
    counterTables.join(';\n') + ';\n',
  ],
]);
for (const [path, body] of outputs) {
  if (process.argv.includes('--write')) writeFileSync(path, body);
  else if (readFileSync(path, 'utf8') !== body)
    throw new Error('Screening counter artifact differs');
}
process.stdout.write(
  JSON.stringify({
    resource: 'screening-counter-artifacts',
    files: outputs.size,
    definitionHash: counterDefinitionHash,
  }) + '\n',
);
